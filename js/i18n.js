let lang = 'am';
try { lang = localStorage.getItem('fhg:lang') === '"en"' ? 'en' : 'am'; } catch { /* storage unavailable */ }

export const getLang = () => lang;
export const locale = () => (lang === 'am' ? 'am-ET' : 'en-GB');

export function setLang(next) {
  lang = next === 'en' ? 'en' : 'am';
  try { localStorage.setItem('fhg:lang', JSON.stringify(lang)); } catch { /* storage unavailable */ }
  applyStatic();
}

export function t(key, vars) {
  let s = WORDS[lang][key] ?? WORDS.en[key] ?? key;
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.replace(`{${k}}`, v);
  return s;
}

// Fill every element marked with data-i18n (text), data-i18n-ph (placeholder) or data-i18n-aria (label).
export function applyStatic() {
  document.documentElement.lang = lang;
  document.querySelectorAll('[data-i18n]').forEach((el) => { el.textContent = t(el.dataset.i18n); });
  document.querySelectorAll('[data-i18n-ph]').forEach((el) => { el.placeholder = t(el.dataset.i18nPh); });
  document.querySelectorAll('[data-i18n-aria]').forEach((el) => { el.setAttribute('aria-label', t(el.dataset.i18nAria)); });
  document.querySelectorAll('[data-i18n-title]').forEach((el) => { el.title = t(el.dataset.i18nTitle); });
  const btn = document.getElementById('lang');
  if (btn) btn.textContent = lang === 'am' ? 'EN' : 'አማ';
}
