-- For His Glory app: prayer replies and owner stats (added October 2026).
-- Run once in Supabase → SQL Editor. Safe to run again.

-- ---------- Replies under prayers ----------
create table if not exists public.prayer_replies (
  id         bigint generated by default as identity primary key,
  prayer_id  bigint not null references public.prayers (id) on delete cascade,
  name       text check (name is null or char_length(name) between 1 and 60),
  message    text not null check (char_length(message) between 1 and 600),
  hidden     boolean not null default false,
  created_at timestamptz not null default now()
);
create index if not exists prayer_replies_prayer_idx on public.prayer_replies (prayer_id);
alter table public.prayer_replies enable row level security;

drop policy if exists "read replies" on public.prayer_replies;
create policy "read replies" on public.prayer_replies for select using (
  public.is_owner() or (not hidden and exists (select 1 from public.prayers p where p.id = prayer_id and not p.hidden))
);
drop policy if exists "write reply" on public.prayer_replies;
create policy "write reply" on public.prayer_replies for insert with check (
  not hidden and exists (select 1 from public.prayers p where p.id = prayer_id and not p.hidden)
);
drop policy if exists "owner replies update" on public.prayer_replies;
create policy "owner replies update" on public.prayer_replies for update using (public.is_owner()) with check (public.is_owner());
drop policy if exists "owner replies delete" on public.prayer_replies;
create policy "owner replies delete" on public.prayer_replies for delete using (public.is_owner());

do $$ begin
  alter publication supabase_realtime add table public.prayer_replies;
exception when others then null; end $$;

-- ---------- Simple, anonymous usage counts for the owner ----------
create table if not exists public.app_stats (
  day   date not null,
  kind  text not null check (kind in ('open', 'play', 'share', 'install')),
  count int  not null default 0,
  primary key (day, kind)
);
alter table public.app_stats enable row level security;
-- No one reads this table directly; the owner sees it through owner_stats().

create or replace function public.track(p_kind text) returns void
language plpgsql security definer set search_path = public as $$
begin
  if p_kind not in ('open', 'play', 'share', 'install') then return; end if;
  insert into public.app_stats (day, kind, count) values (public.today_local(), p_kind, 1)
  on conflict (day, kind) do update set count = public.app_stats.count + 1;
end $$;

create or replace function public.owner_stats() returns json
language plpgsql stable security definer set search_path = public as $$
declare result json;
begin
  if not public.is_owner() then raise exception 'not allowed'; end if;
  select json_build_object(
    'subscribers', (select count(*) from public.push_subscriptions),
    'amens',       (select coalesce(sum(amens), 0) from public.bread),
    'prayers',     (select count(*) from public.prayers),
    'prayed',      (select coalesce(sum(prayed), 0) from public.prayers),
    'replies',     (select count(*) from public.prayer_replies),
    'comments',    (select count(*) from public.comments),
    'bread',       (select count(*) from public.bread where posted_on <= public.today_local()),
    'scheduled',   (select count(*) from public.bread where posted_on > public.today_local()),
    'days', (
      select coalesce(json_agg(d order by d.day), '[]'::json) from (
        select g::date as day,
          coalesce((select count from public.app_stats s where s.day = g::date and s.kind = 'open'), 0) as opens,
          coalesce((select count from public.app_stats s where s.day = g::date and s.kind = 'play'), 0) as plays,
          coalesce((select count from public.app_stats s where s.day = g::date and s.kind = 'share'), 0) as shares,
          coalesce((select count from public.app_stats s where s.day = g::date and s.kind = 'install'), 0) as installs
        from generate_series(public.today_local() - 13, public.today_local(), interval '1 day') g
      ) d
    )
  ) into result;
  return result;
end $$;

revoke execute on function public.track(text) from public;
revoke execute on function public.owner_stats() from public;
grant execute on function public.track(text) to anon, authenticated;
grant execute on function public.owner_stats() to authenticated;
